"""Incident dossier and containment action data models."""

from __future__ import annotations
from enum import Enum
from typing import Any, Dict, List, Optional
from datetime import datetime, timezone
from pydantic import BaseModel, Field
from .ocsf import FindingEvent, OCSFEvent


class AlertStatus(str, Enum):
    UNTRIAGED = "UNTRIAGED"
    FALSE_POSITIVE = "FALSE_POSITIVE"
    TRIAGED_ESCALATED = "TRIAGED_ESCALATED"
    INVESTIGATING = "INVESTIGATING"
    CONTAINMENT_PROPOSED = "CONTAINMENT_PROPOSED"
    CONTAINED = "CONTAINED"
    CLOSED = "CLOSED"


class ActionSeverity(str, Enum):
    LOW = "LOW"             # e.g., temporary IP throttle, log verbosity increase
    MEDIUM = "MEDIUM"       # e.g., session termination, quarantine file
    HIGH = "HIGH"           # e.g., account lock, perimeter IP block
    CRITICAL = "CRITICAL"   # e.g., full host isolation, identity revocation, enterprise-wide credential reset


class ApprovalStatus(str, Enum):
    PENDING = "PENDING"
    AUTOMATICALLY_APPROVED = "AUTOMATICALLY_APPROVED"
    MANUALLY_APPROVED = "MANUALLY_APPROVED"
    REJECTED = "REJECTED"


class ContainmentAction(BaseModel):
    """Specific defensive response action generated by HunterAgent."""
    action_id: str
    target_entity: str
    target_type: str  # host, user, ip, file, process
    action_type: str  # host_isolation, credential_revocation, firewall_block_ip, process_kill
    reason: str
    severity: ActionSeverity = ActionSeverity.MEDIUM
    requires_hitl: bool = False
    approval_status: ApprovalStatus = ApprovalStatus.PENDING
    approver: Optional[str] = None
    executed: bool = False
    execution_result: Optional[str] = None
    audit_hash: Optional[str] = None


class IncidentDossier(BaseModel):
    """Structured security incident dossier passed across SOC tiers."""
    incident_id: str
    title: str
    summary: str
    initial_finding: FindingEvent
    entity_id: str
    entity_type: str
    anomaly_score: float = 0.0
    baseline_deviations: List[str] = Field(default_factory=list)
    evidence_events: List[OCSFEvent] = Field(default_factory=list)
    mitre_techniques: List[str] = Field(default_factory=list)
    blast_radius_score: float = 0.0
    status: AlertStatus = AlertStatus.UNTRIAGED
    containment_actions: List[ContainmentAction] = Field(default_factory=list)
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def update_status(self, new_status: AlertStatus) -> None:
        self.status = new_status
        self.updated_at = datetime.now(timezone.utc).isoformat()
